export type NameDayEntry = { mmdd: string; names: string[] };

/** Names celebrated today in Europe/Athens. Empty array on days with
 *  no entry — caller should hide the chip rather than show "none".
 *  Computed against Athens local date, not the visitor's clock, so the
 *  Greek calendar reads consistently across timezones. */
export function getNameDays(at: Date = new Date()): string[] {
  return NAMES_BY_DATE[athensMMDD(at)] ?? [];
}

/** "MM-DD" in Europe/Athens — independent of the visitor's TZ. */
function athensMMDD(at: Date): string {
  const fmt = new Intl.DateTimeFormat('en-GB', {
    timeZone: 'Europe/Athens',
    month: '2-digit',
    day: '2-digit',
  });
  // Returns "DD/MM" → reorder to "MM-DD".
  const parts = fmt.formatToParts(at);
  const m = parts.find((p) => p.type === 'month')?.value ?? '01';
  const d = parts.find((p) => p.type === 'day')?.value ?? '01';
  return `${m}-${d}`;
}

/** All entries in the calendar — used by tests + future "upcoming"
 *  features ("next name day in 3 days: Βασίλης"). */
export function allNameDays(): NameDayEntry[] {
  return Object.entries(NAMES_BY_DATE)
    .map(([mmdd, names]) => ({ mmdd, names }))
    .sort((a, b) => a.mmdd.localeCompare(b.mmdd));
}
